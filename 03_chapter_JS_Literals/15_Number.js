//Integer literals

let decimal_value=10;
console.log("decimal value is:", decimal_value);

let binary= 0b1010;
console.log("binary value is:", binary); //10

let octal=0o52;
console.log("octal value is:", octal); //42

let hexadecimal=0x2A;
console.log("hexadecimal value is:", hexadecimal); //42

//floating literals

let floating_value= 3.14;
let floating_value2= -0.53;
let floating_value3= .9;
let floating_value4= 9.;

console.log("floating value is:", floating_value); 
console.log("floating value is:", floating_value2);
console.log("floating value is:", floating_value3);
console.log("floating value is:", floating_value4);

//exponential literals

let exponential_value= 1.5e4;
let exponential_value2= 1.5e-4;
let exponential_value3= 1.5E4;

console.log("exponential value is:", exponential_value);
console.log("exponential value is:", exponential_value2);
console.log("exponential value is:", exponential_value3);